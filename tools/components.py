def стем(w):
    return w.lower().strip(".,;:!?()«»\"'’- ").replace("’", "").replace("ʼ", "")


def шукати(запит):
    """Анімації, що підходять під слова задачі. Повертає [(бали, селектор)]."""
    qs = [стем(w) for w in re.split(r"[\s,;/]+", запит)
          if len(стем(w)) >= 3 and стем(w) not in СТОП]
    out = []
    for sel, a in ANIM.items():
        полe = " ".join([a["слова"], a["коли"], a["що"]])
        ws = [стем(w) for w in re.split(r"[\s,;/]+", полe) if стем(w)]
        бали = 0
        for q in qs:
            for w in ws:
                n = min(len(q), len(w), 5)
                if n >= 3 and q[:n] == w[:n]:
                    бали += 1
                    break
        if бали:
            out.append((бали, sel))
    return sorted(out, reverse=True)


def друк_анімації(where, тільки=None):
    print("Анімації — показують те, що учень має зрозуміти, а не просто рухаються:")
