def стем(w):
    return w.lower().strip(".,;:!?()«»\"'’- ").replace("’", "").replace("ʼ", "")


def шукати(запит):
    """Анімації, що підходять під слова задачі. Повертає [(бали, селектор)]."""
    qs = [стем(w) for w in re.split(r"[\s,;/]+", запит)
          if len(стем(w)) >= 3 and стем(w) not in СТОП]
    out = []
    for sel, a in ANIM.items():
        полe = " ".join([a["слова"], a["коли"], a["що"]])
        ws = [стем(w) for w in re.split(r"[\s,;/]+", полe) if стем(w)]
        бали = 0
        for q in qs:
            for w in ws:
                n = min(len(q), len(w), 5)
                if n >= 3 and q[:n] == w[:n]:
                    бали += 1
                    break
        if бали:
            out.append((бали, sel))
    return sorted(out, reverse=True)


def друк_анімації(where, тільки=None):
    print("Анімації — показують те, що учень має зрозуміти, а не просто рухаються:")
    for sel in (тільки or sorted(ANIM)):
        a = ANIM[sel]
        loc = where.get(sel[1:])
        print(f"  {sel:<9s} {a['що']}")
        print(f"  {'':<9s} коли: {a['коли']}   клас: {a['клас']}")
        print(f"  {'':<9s} {a['розмітка']}")
        print(f"  {'':<9s} " + (f"шаблон, слайд {loc[0]} «{loc[1]}»" if loc else "У ШАБЛОНІ НЕ ПОКАЗАНО"))
    print()


def js_components(js):
    """Компоненти, які двигун ініціалізує сам: $$('.щось').forEach(...)"""
    found = set(re.findall(r"\$\$\('\.([a-z][\w-]*)'\)\.forEach", js))
    # .steps оживляє syncSteps() на кожному кроці: $$('.steps', s)
    found |= set(re.findall(r"\$\$\('\.([a-z][\w-]*)',\s*s\)\.forEach", js))
    found.discard("hide")                       # .hide — механіка кроків, не компонент
    return sorted(found)


def css_selectors(css):
    return set(re.findall(r"^\s*\.([a-z][\w-]*)", css, re.M))


def template_slides(html):
    """{клас: (номер слайда, заголовок)} — де компонент показано в шаблоні."""
    out = {}
    slides = re.findall(r"<section class=\"slide[^\"]*\"[^>]*data-t=\"([^\"]*)\"[^>]*>(.*?)</section>",
                        html, re.S)
    for i, (title, body) in enumerate(slides, 1):
        for cls in set(re.findall(r'class="([^"]*)"', body)):
            for c in cls.split():
                out.setdefault(c, (i, title))
        for attr in re.findall(r'\b(data-timer|data-chapter)=', body):
            out.setdefault(attr, (i, title))
    return out


